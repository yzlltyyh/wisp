/** 模板对应的品牌标志；没有模板、模板没有登记标志（含中转站）时为 null */
export function brandLogo(templateId: string | null | undefined): BrandLogo | null {
  if (!templateId || !Object.hasOwn(PROVIDER_LOGOS, templateId)) return null
  return PROVIDER_LOGOS[templateId as BrandTemplateId]
}

/** 深色主题下换用的颜色：写在 --dk 上，settings.css 在 [data-theme='dark'] 下取用 */
function darkAttrs(dark: string | undefined) {
  return dark ? { 'data-dk': '', style: { '--dk': dark } as CSSProperties } : {}
}

function BrandMark({ logo, size }: { logo: BrandLogo; size: number }) {
  // 渐变 id 要在整个文档里唯一：同一页可能同时有几个相同的标志（列表、模板选择）
  const uid = useId()
  return (
    <svg
      className="st-logo-mark"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fillRule={logo.evenOdd ? 'evenodd' : undefined}
      focusable={false}
    >
      {logo.gradients ? (
        <defs>
          {logo.gradients.map((g, i) => (
            <linearGradient
              // oxlint-disable-next-line react/no-array-index-key -- 静态数据，顺序不变；路径按序号引用渐变
              key={i}
              id={`${uid}g${i}`}
              gradientUnits="userSpaceOnUse"
              x1={g.from[0]}
              y1={g.from[1]}
              x2={g.to[0]}
              y2={g.to[1]}
            >
              {g.stops.map((s) => (
                <stop
                  key={s.offset}
                  offset={s.offset}
                  stopColor={s.color}
                  stopOpacity={s.opacity}
                  {...darkAttrs(s.dark)}
                />
              ))}
            </linearGradient>
          ))}
        </defs>
      ) : null}
      {logo.paths.map((p, i) => (
        <path
          // oxlint-disable-next-line react/no-array-index-key -- 静态数据，顺序不变（Gemini 的几层路径相同，不能用 d 作 key）
          key={i}
          d={p.d}
          fill={
            p.gradient === undefined ? (p.fill ?? 'currentColor') : `url(#${uid}g${p.gradient})`
          }
          fillOpacity={p.opacity}
          {...darkAttrs(p.dark)}
        />
      ))}
    </svg>
  )
}

/**
 * 服务头像（.st-logo 方块，读屏不念：旁边总有可见的服务名）：有品牌标志的画标志，中转站画中性图标，
 * 其余退回两字母头像。品牌标志与中转站图标一律放在中性底上（品牌色不和强调色叠在一起）；`tone` 只决定两字母头像的底色。
 * `size` 是标志的边长：28 px 的头像用 16，36 px 的用 20。
 */
export function ProviderLogo({
  templateId,
  name,
  size = 16,
  tone = 'accent',
  className,
}: {
  templateId: string | null | undefined
  /** 两字母头像由它生成 */
  name: string
  size?: number
  tone?: 'accent' | 'neutral'
  className?: string
}) {
  const logo = brandLogo(templateId)
  const relay = templateId === RELAY_TEMPLATE
  return (
    <span
      className={className ? `st-logo ${className}` : 'st-logo'}
      data-tone={logo || relay ? 'neutral' : tone}
      data-brand={logo ? templateId : undefined}
      aria-hidden="true"
    >
      {logo ? (
        <BrandMark logo={logo} size={size} />
      ) : relay ? (
        <Icon icon={Waypoints} size={size} />
      ) : (
        monogram(name)
      )}
    </span>
  )
}
