//! Wisp 的纯文本规则。
//!
//! OCR 的文本拼装、剪贴板的文本变换等多处要对同一段文字做同样的判断（两段文字之间要不要空格、行尾的连字符
//! 是不是断词、一行是不是列表项），规则集中在这里，各处的结果才能一致。
//!
//! 只放确定性的纯文本规则：同样的输入总是同样的输出，不做 I/O，不依赖任何 crate（包括 `wisp-types`）。
//! 版面、几何与识别模式由调用方处理，需要时只把折算出的数值传进来（例如 [`join::needs_space`] 的间距）。
//!
//! ## 模块
//!
//! - [`script`]：字符按书写习惯分类（哪些文字不用空格分词、哪些是谚文、哪些属于中日韩文字）；
//! - [`join`]：两段文字拼接——同一视觉行内的片段是否加空格、跨行续接（[`join::join_break`]：断词还原、东亚标点、
//!   中英混排按全文惯例）、列表项的判定；
//! - [`lines`]：整段文字按行处理的操作（识别结果的默认整理、去掉空行、合成一行），以及各处共用的断行
//!   （[`lines::split_lines`]：`\n`、`\r\n`、单独的 `\r` 都是换行）；
//! - [`stream`]：流式到达的文字的增量整理（与 [`lines`] 里对应的整段版本结果相同）。

pub mod join;
pub mod lines;
pub mod script;
pub mod stream;
