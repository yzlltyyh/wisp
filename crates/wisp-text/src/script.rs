//! 字符按书写习惯分类。
//!
//! 三个判定各管一件事，范围互不替代：
//!
//! - [`is_unspaced`]：不用空格分词的东亚文字与标点（汉字、假名、注音、CJK 标点、全角形式等）。跨行拼接时两侧都是
//!   这类字符就直接相连；
//! - [`is_hangul`]：谚文。韩文以空格分词，拼接时与拉丁文同等对待；
//! - [`is_east_asian`]：两者之和，回答「这段文字里有没有中日韩文字」（例如全角变换是否值得提供）。
//!
//! 语言检测（只看字母、要区分中日韩）、显示宽度（缩进与窗口排版要的是占几个半角宽）的语义不同，各自另有判定，
//! 不并进这里。

/// 是否是不用空格分词的东亚文字或标点：彼此相邻时不加空格，跨行续接时直接相连。包含
///
/// - 汉字：基本区、扩展 A、扩展 B 及以后（含兼容汉字补充）、兼容汉字，以及 CJK 部首、康熙部首、汉字结构描述符、笔画；
/// - 假名：平假名、片假名（含语音扩展、半角片假名与假名补充 / 扩展区）；注音（含扩展）与汉文训读符号；
/// - CJK 符号与标点（不含 U+3000 全角空格，它是空白）、竖排标点、CJK 兼容形式；
/// - 带圈与括号的 CJK 字母和月份（㈱）、CJK 兼容字符（㎏）；
/// - 全角形式（全角 ASCII、全角括号、全角货币符号）与半角 CJK 标点。
///
/// 不含谚文（见 [`is_hangul`]），也不含中西文共用的通用标点（`—`、`…`、`“`、`·` 等）：它们属于哪种书写习惯要看
/// 上下文，由调用方判断。
#[inline]
pub fn is_unspaced(c: char) -> bool {
    matches!(
        c as u32,
        0x2E80..=0x2FFF      // CJK 部首补充、康熙部首、汉字结构描述符
            | 0x3001..=0x303F // CJK 符号与标点（U+3000 是空白，不算）
            | 0x3040..=0x30FF // 平假名、片假名
            | 0x3100..=0x312F // 注音
            | 0x3190..=0x31FF // 汉文训读、注音扩展、CJK 笔画、片假名语音扩展
            | 0x3200..=0x33FF // 带圈与括号的 CJK 字母和月份、CJK 兼容字符
            | 0x3400..=0x4DBF // 扩展 A
            | 0x4E00..=0x9FFF // 基本汉字
            | 0xF900..=0xFAFF // 兼容汉字
            | 0xFE10..=0xFE1F // 竖排标点
            | 0xFE30..=0xFE4F // CJK 兼容形式
            | 0xFF01..=0xFF60 // 全角 ASCII 与全角括号
            | 0xFF61..=0xFF9F // 半角 CJK 标点与半角片假名
            | 0xFFE0..=0xFFE6 // 全角货币与符号
            | 0x1AFF0..=0x1B16F // 假名扩展 B、假名补充、假名扩展 A、小假名扩展
            | 0x20000..=0x3FFFD // 扩展 B 及以后、兼容汉字补充
    )
}

/// 是否是谚文：谚文字母（含扩展 A / B）、兼容字母、音节与半角谚文字母。
///
/// 韩文以空格分词，跨行续接时与拉丁文一样补空格；带圈与括号的谚文（㉠、㈀）是符号，归在 [`is_unspaced`]。
#[inline]
pub fn is_hangul(c: char) -> bool {
    matches!(
        c as u32,
        0x1100..=0x11FF      // 谚文字母
            | 0x3130..=0x318F // 谚文兼容字母
            | 0xA960..=0xA97F // 谚文字母扩展 A
            | 0xAC00..=0xD7FF // 谚文音节、谚文字母扩展 B
            | 0xFFA0..=0xFFDC // 半角谚文字母
    )
}

/// 是否是中日韩文字或标点：[`is_unspaced`] 与 [`is_hangul`] 之和。用来判断一段文字里有没有中日韩文字，
/// 不用来决定拼接时加不加空格（那要区分两者）。
#[inline]
pub fn is_east_asian(c: char) -> bool {
    is_unspaced(c) || is_hangul(c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn east_asian_scripts_without_word_spaces() {
        // 汉字（含扩展 B、G 与兼容汉字）、假名（含半角与假名补充）、注音、部首与笔画、CJK 标点、全角形式、
        // 竖排标点、CJK 兼容字符
        for c in "汉㐀𠀀𠮷𰀀豈あカㇰｶㄅㆠ⺀⿰㇀、。「（，Ａ１｡︵︐㈱㎏￥\u{1B001}".chars()
        {
            assert!(is_unspaced(c), "{c:?}");
            assert!(is_east_asian(c), "{c:?}");
            assert!(!is_hangul(c), "{c:?}");
        }
    }

    #[test]
    fn hangul_is_east_asian_but_spaced() {
        for c in ['한', '글', 'ᄀ', 'ㄱ', 'ꥠ', 'ힰ', 'ﾡ'] {
            assert!(is_hangul(c), "{c:?}");
            assert!(is_east_asian(c), "{c:?}");
            assert!(!is_unspaced(c), "{c:?}");
        }
    }

    #[test]
    fn spaced_scripts_whitespace_and_shared_punctuation() {
        // 拉丁、西里尔字母与数字；全角空格是空白；破折号、省略号、弯引号、间隔号是中西文共用的标点，要看上下文
        for c in [
            'a', 'Z', '1', 'é', 'Ж', ' ', '\u{3000}', '-', '—', '…', '“', '·', '•', '\u{FF00}', '\u{FFE8}',
        ] {
            assert!(!is_east_asian(c), "{c:?}");
        }
    }
}
